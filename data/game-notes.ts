function exclusiveGroupTable(groups = exclusiveGroups) {
  const rows = groups.map(({ group, members }) => {
    const routeA = members.find((quest) => quest.exclusiveRoute === "A");
    const routeB = members.find((quest) => quest.exclusiveRoute === "B");
    const label = (quest?: Quest) => quest ? `${quest.name}（\`${quest.id}\`）` : "—";
    return `| ${group} | ${label(routeA)} | ${label(routeB)} |`;
  });
  return ["| 互斥组 | 路线 A | 路线 B |", "| --- | --- | --- |", ...rows].join("\n");
}

