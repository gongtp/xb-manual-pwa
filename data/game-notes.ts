function deadlineRisk(quest: Quest) {
  return quest.notes.match(/截止点\/风险：([^；]+)/)?.[1] ?? "未标注截止点";
}

const timedQuests = (xc1QuestData as Quest[])
  .filter((quest) => quest.game === "XC1" && quest.isTimed)
  .sort((left, right) => left.id.localeCompare(right.id, "zh-CN", { numeric: true }));

function tasksWithRisk(...risks: string[]) {
  const accepted = new Set(risks);
  return timedQuests.filter((quest) => accepted.has(deadlineRisk(quest)));
}

function taskChecklist(quests: Quest[]) {
  return quests.map((quest) => `- [ ] ${quest.name}（\`${quest.id}\`）`).join("\n");
}

