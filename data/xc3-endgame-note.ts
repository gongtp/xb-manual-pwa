雅乐士自带神速旋律，不用再给别人重复装；丰收大海也只需要全队一份。辉煌旋律能为其他队员回填战技，并暂停增益时间；手动操作时，等队友消耗一轮战技后再使用，比全员满槽时空放划算。圣奈仍负责浮空路线，兰兹的眩晕只作为救场或切换爆裂打法的备用。

